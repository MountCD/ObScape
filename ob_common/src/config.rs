/// Сырые переопределения путей, полученные из CLI / ENV.
/// Разбираются один раз в `main` через [`parse_cli`] и передаются дальше.
/// Поля приватные — снаружи структура непрозрачна.
#[derive(Debug, Default, Clone)]
pub struct PathOverrides {
    /// Путь до `config.toml` (CLI или ENV).
    config: Option<String>,
    /// Database URL (CLI или ENV).
    database: Option<String>,
    /// Запрошен ли `--init` (генерация шаблона и открытие в редакторе).
    init: bool,
    /// Запрошен ли `--verbose` (подробный вывод).
    verbose: bool,
    /// Запрошен ли `--allow-autogenerated` (стартовать с неотредактированным
    /// шаблоном конфига, игнорируя `autogenerated = true`).
    allow_autogenerated: bool,
    /// Запрошен ли `--print-config` (после `--print-config` нужно выйти).
    print_config: bool,
    /// Запрошен ли `--help` / `-h`.
    help: bool,
}

impl PathOverrides {
    /// Запрошен ли `--help` / `-h`.
    pub fn help(&self) -> bool {
        self.help
    }

    /// Запрошен ли `--init`.
    pub fn init(&self) -> bool {
        self.init
    }

    /// Запрошен ли `--print-config`.
    pub fn print_config(&self) -> bool {
        self.print_config
    }
}

