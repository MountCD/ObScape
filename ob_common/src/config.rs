use serde::Deserialize;
use std::env;
use std::fs;
use std::io::Write;

#[derive(Debug, Deserialize, Clone)]
pub struct AgentConfig {
    pub enabled: bool,
    /// Агент по умолчанию: используется, когда в `POST /v1/chat/new`
    /// не передан `agent`. Не больше одного включённого агента с `main = true`.
    #[serde(default)]
    pub main: bool,
    pub model_id: String,
    pub api_url: String,
    /// Ключ апстрима. Можно не указывать в TOML и задать через
    /// `OBSISTENT_AGENT_<ИМЯ>_API_KEY` (env имеет приоритет). Пустая
    /// строка считается отсутствием ключа.
    #[serde(default)]
    pub api_key: String,
    pub personality_prompt: String,
    /// Таймаут одного запроса к апстриму в секундах (разным моделям
    /// нужно разное время). Дефолт — `DEFAULT_TIMEOUT_SECS`.
    #[serde(default = "default_timeout_secs")]
    pub timeout_secs: u64,
}

/// Дефолт для `timeout_secs`, если поле не задано в config.toml.
pub const DEFAULT_TIMEOUT_SECS: u64 = 120;

fn default_timeout_secs() -> u64 {
    DEFAULT_TIMEOUT_SECS
}
impl AgentConfig {
    /// Системный промпт чата: общий + личный, через пустую строку,
    /// чтобы многострочные промпты не слипались.
    pub fn merge_config(&self, shared: &str) -> String {
        format!("{}\n\n{}", shared, self.personality_prompt)
    }
}
#[derive(Debug, Deserialize, Clone)]
pub struct Config {
    /// Маркер неотредактированного шаблона от `--init`. В рукописном
    /// конфиге поле можно не указывать.
    #[serde(default)]
    pub autogenerated: bool,
    pub database_url: String,
    /// Адрес и порт HTTP-сервера (например, `0.0.0.0:11080`).
    /// `None` означает "использовать дефолт".
    pub http_bind: Option<String>,
    #[serde(default)]
    pub verbose: bool,
    pub shared_prompt: String,
    /// Сколько последних сообщений (без учёта системного промпта)
    /// отправлять модели. Ограничивает рост запроса на длинных чатах.
    #[serde(default = "default_history_limit")]
    pub history_limit: u32,
    pub agents: std::collections::HashMap<String, AgentConfig>,
}

impl Config {
    /// Ключ включённого агента с `main = true`, если такой есть.
    pub fn main_agent(&self) -> Option<&str> {
        self.agents
            .iter()
            .find(|(_, a)| a.enabled && a.main)
            .map(|(name, _)| name.as_str())
    }
}

/// Дефолт для `history_limit`, если поле не задано в config.toml.
pub const DEFAULT_HISTORY_LIMIT: u32 = 50;

fn default_history_limit() -> u32 {
    DEFAULT_HISTORY_LIMIT
}

/// Ошибки загрузки/парсинга конфигурации.
#[derive(Debug)]
pub enum ConfigError {
    Autogenerated,
    Io(std::io::Error),
    Parse(toml::de::Error),
    MissingField(&'static str),
    InvalidArgs(String),
    /// Конфиг разобран, но содержит противоречие.
    Invalid(String),
    /// Не удалось определить домашнюю директорию (нет `$HOME`).
    NoHomeDir,
}

impl std::fmt::Display for ConfigError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            ConfigError::Autogenerated => write!(f, "Config is autogenerated. Redact it firstly."),
            ConfigError::Io(e) => write!(f, "failed to read config: {e}"),
            ConfigError::Parse(e) => write!(f, "failed to parse TOML: {e}"),
            ConfigError::MissingField(name) => write!(f, "missing field `{name}` in config"),
            ConfigError::InvalidArgs(msg) => write!(f, "{msg}"),
            ConfigError::Invalid(msg) => write!(f, "invalid config: {msg}"),
            ConfigError::NoHomeDir => write!(
                f,
                "cannot determine home directory; set $HOME or pass --config / {ENV_CONFIG}"
            ),
        }
    }
}

impl std::error::Error for ConfigError {}

/// Дефолтная директория конфигурации (`$HOME/.config/obscape`).
fn make_conf_path() -> Result<String, ConfigError> {
    let home = env::home_dir()
        .and_then(|h| h.into_os_string().into_string().ok())
        .ok_or(ConfigError::NoHomeDir)?;
    let out = format!("{home}/.config/obscape");
    Ok(out)
}

pub fn make_file_path() -> Result<String, ConfigError> {
    Ok(format!("{}/config.toml", make_conf_path()?))
}

pub fn format_conf_path(path: String) -> String {
    format!("{}/config.toml", path)
}

/// Дефолтный адрес HTTP-сервера.
const DEFAULT_HTTP_BIND: &str = "0.0.0.0:11080";

/// Переменные окружения, которые читаются как fallback.
const ENV_CONFIG: &str = "OBSISTENT_CONFIG";
const ENV_DATABASE: &str = "OBSISTENT_DATABASE";

/// Имя переменной окружения с ключом апстрима для агента `name`:
/// `OBSISTENT_AGENT_<NAME>_API_KEY`, где имя приводится к верхнему регистру,
/// а всё, кроме букв и цифр, заменяется на `_`.
pub fn agent_api_key_env(name: &str) -> String {
    let norm: String = name
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_uppercase()
            } else {
                '_'
            }
        })
        .collect();
    format!("OBSISTENT_AGENT_{norm}_API_KEY")
}
